-- =====================================================================
-- TiCuida - Modelo físico do banco de dados
-- SGBD alvo: PostgreSQL 16 (produção). Em desenvolvimento o mesmo
-- modelo é criado em SQLite pelo Flask-SQLAlchemy/Flask-Migrate.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Convênios aceitos (inclui o registro "Particular")
-- ---------------------------------------------------------------------
CREATE TABLE convenios (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_convenios_nome UNIQUE (nome)
);

-- ---------------------------------------------------------------------
-- Unidades de saúde (carregadas por seed no MVP)
-- ---------------------------------------------------------------------
CREATE TABLE unidades (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(150) NOT NULL,
    tipo                VARCHAR(20)  NOT NULL,
    telefone            VARCHAR(20),
    logradouro          VARCHAR(150) NOT NULL,
    numero              VARCHAR(10)  NOT NULL,
    bairro              VARCHAR(80)  NOT NULL,
    cidade              VARCHAR(80)  NOT NULL,
    uf                  CHAR(2)      NOT NULL,
    cep                 CHAR(8),
    latitude            NUMERIC(9,6) NOT NULL,
    longitude           NUMERIC(9,6) NOT NULL,
    aberto_24h          BOOLEAN      NOT NULL DEFAULT FALSE,
    horario_abertura    TIME,
    horario_fechamento  TIME,
    ativo               BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_unidades_tipo      CHECK (tipo IN ('pronto_atendimento', 'clinica', 'hospital')),
    CONSTRAINT ck_unidades_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_unidades_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_unidades_horario   CHECK (aberto_24h OR (horario_abertura IS NOT NULL AND horario_fechamento IS NOT NULL))
);

-- Associação N:N unidade x convênio aceito
CREATE TABLE unidade_convenio (
    unidade_id   INTEGER NOT NULL,
    convenio_id  INTEGER NOT NULL,
    CONSTRAINT pk_unidade_convenio PRIMARY KEY (unidade_id, convenio_id),
    CONSTRAINT fk_unidade_convenio_unidade  FOREIGN KEY (unidade_id)  REFERENCES unidades (id)  ON DELETE CASCADE,
    CONSTRAINT fk_unidade_convenio_convenio FOREIGN KEY (convenio_id) REFERENCES convenios (id) ON DELETE CASCADE
);
CREATE INDEX ix_unidade_convenio_convenio ON unidade_convenio (convenio_id);

-- ---------------------------------------------------------------------
-- Usuários (login). Papel: paciente ou operador.
-- Operador obrigatoriamente vinculado a uma unidade; paciente nunca.
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    senha_hash    VARCHAR(255) NOT NULL,
    papel         VARCHAR(10)  NOT NULL,
    unidade_id    INTEGER,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_papel CHECK (papel IN ('paciente', 'operador')),
    CONSTRAINT ck_usuarios_operador_unidade CHECK (
        (papel = 'operador' AND unidade_id IS NOT NULL) OR
        (papel = 'paciente' AND unidade_id IS NULL)
    ),
    CONSTRAINT fk_usuarios_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id) ON DELETE RESTRICT
);
CREATE INDEX ix_usuarios_unidade ON usuarios (unidade_id);

-- ---------------------------------------------------------------------
-- Pacientes (perfil 1:1 com usuário de papel 'paciente')
-- ---------------------------------------------------------------------
CREATE TABLE pacientes (
    id                           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id                   INTEGER      NOT NULL,
    nome                         VARCHAR(150) NOT NULL,
    cpf                          CHAR(11)     NOT NULL,
    data_nascimento              DATE         NOT NULL,
    telefone                     VARCHAR(20)  NOT NULL,
    contato_emergencia_nome      VARCHAR(150) NOT NULL,
    contato_emergencia_telefone  VARCHAR(20)  NOT NULL,
    convenio_id                  INTEGER      NOT NULL,
    numero_carteirinha           VARCHAR(30),
    consentimento_em             TIMESTAMPTZ  NOT NULL,
    criado_em                    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_pacientes_usuario UNIQUE (usuario_id),
    CONSTRAINT uq_pacientes_cpf     UNIQUE (cpf),
    CONSTRAINT ck_pacientes_cpf     CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT fk_pacientes_usuario  FOREIGN KEY (usuario_id)  REFERENCES usuarios (id)  ON DELETE CASCADE,
    CONSTRAINT fk_pacientes_convenio FOREIGN KEY (convenio_id) REFERENCES convenios (id) ON DELETE RESTRICT
);
CREATE INDEX ix_pacientes_convenio ON pacientes (convenio_id);

-- ---------------------------------------------------------------------
-- Catálogo de sintomas. sinal_alarme = TRUE leva à prioridade Emergência.
-- ---------------------------------------------------------------------
CREATE TABLE sintomas (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(80)  NOT NULL,
    descricao     VARCHAR(255),
    sinal_alarme  BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_sintomas_nome UNIQUE (nome)
);

-- ---------------------------------------------------------------------
-- Triagens realizadas pelo paciente
-- ---------------------------------------------------------------------
CREATE TABLE triagens (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id       INTEGER      NOT NULL,
    queixa_principal  VARCHAR(500) NOT NULL,
    intensidade       SMALLINT     NOT NULL,
    inicio_sintomas   VARCHAR(15)  NOT NULL,
    temperatura       NUMERIC(3,1),
    prioridade        VARCHAR(15)  NOT NULL,
    criada_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_triagens_intensidade CHECK (intensidade BETWEEN 0 AND 10),
    CONSTRAINT ck_triagens_inicio      CHECK (inicio_sintomas IN ('menos_24h', '1_a_3_dias', 'mais_3_dias')),
    CONSTRAINT ck_triagens_temperatura CHECK (temperatura IS NULL OR temperatura BETWEEN 34.0 AND 43.0),
    CONSTRAINT ck_triagens_prioridade  CHECK (prioridade IN ('emergencia', 'urgente', 'pouco_urgente', 'nao_urgente')),
    CONSTRAINT fk_triagens_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id) ON DELETE CASCADE
);
CREATE INDEX ix_triagens_paciente_data ON triagens (paciente_id, criada_em DESC);

-- Associação N:N triagem x sintoma marcado
CREATE TABLE triagem_sintoma (
    triagem_id  INTEGER NOT NULL,
    sintoma_id  INTEGER NOT NULL,
    CONSTRAINT pk_triagem_sintoma PRIMARY KEY (triagem_id, sintoma_id),
    CONSTRAINT fk_triagem_sintoma_triagem FOREIGN KEY (triagem_id) REFERENCES triagens (id) ON DELETE CASCADE,
    CONSTRAINT fk_triagem_sintoma_sintoma FOREIGN KEY (sintoma_id) REFERENCES sintomas (id) ON DELETE RESTRICT
);
CREATE INDEX ix_triagem_sintoma_sintoma ON triagem_sintoma (sintoma_id);

-- ---------------------------------------------------------------------
-- Encaminhamentos ("Estou indo"): uma triagem gera no máximo um
-- ---------------------------------------------------------------------
CREATE TABLE encaminhamentos (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triagem_id     INTEGER     NOT NULL,
    unidade_id     INTEGER     NOT NULL,
    protocolo      CHAR(8)     NOT NULL,
    status         VARCHAR(15) NOT NULL DEFAULT 'a_caminho',
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_encaminhamentos_triagem   UNIQUE (triagem_id),
    CONSTRAINT uq_encaminhamentos_protocolo UNIQUE (protocolo),
    CONSTRAINT ck_encaminhamentos_status CHECK (status IN ('a_caminho', 'chegou', 'atendido', 'nao_compareceu')),
    CONSTRAINT fk_encaminhamentos_triagem FOREIGN KEY (triagem_id) REFERENCES triagens (id) ON DELETE CASCADE,
    CONSTRAINT fk_encaminhamentos_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id) ON DELETE RESTRICT
);
-- Fila da unidade: filtra por unidade e status, ordena por horário
CREATE INDEX ix_encaminhamentos_fila ON encaminhamentos (unidade_id, status, criado_em);

-- ---------------------------------------------------------------------
-- Histórico de lotação informado pelo operador (o atual é o mais recente)
-- ---------------------------------------------------------------------
CREATE TABLE registros_lotacao (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id     INTEGER     NOT NULL,
    operador_id    INTEGER     NOT NULL,
    nivel          VARCHAR(5)  NOT NULL,
    registrado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_registros_lotacao_nivel CHECK (nivel IN ('baixa', 'media', 'alta')),
    CONSTRAINT fk_registros_lotacao_unidade  FOREIGN KEY (unidade_id)  REFERENCES unidades (id) ON DELETE CASCADE,
    CONSTRAINT fk_registros_lotacao_operador FOREIGN KEY (operador_id) REFERENCES usuarios (id) ON DELETE RESTRICT
);
CREATE INDEX ix_registros_lotacao_unidade_data ON registros_lotacao (unidade_id, registrado_em DESC);
CREATE INDEX ix_registros_lotacao_operador ON registros_lotacao (operador_id);

COMMIT;
